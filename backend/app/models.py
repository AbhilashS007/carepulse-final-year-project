# TABLE 3: urination_events
# ================================================================

class UrinationEvent(Base):
    """
    A single sensor reading captured from the IoT smart diaper.

    Each record represents one snapshot:
    - Current wetness level and percentage
    - Current device battery and status

    These records are the raw time-series data used to:
    - Drive the real-time dashboard wetness trend chart
    - Calculate daily urination frequency
    - Feed the AI pattern analysis engine
    """

    __tablename__ = "urination_events"

    # Primary key
    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)

    # Foreign key to the patient this reading belongs to
    patient_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("patients.id", ondelete="CASCADE"), nullable=False, index=True
    )

    # Wetness measurement from the capacitive sensor (0–100 %)
    wetness_percent: Mapped[float] = mapped_column(Float, nullable=False)

    # Categorised wetness label computed from wetness_percent
    wetness_level: Mapped[str] = mapped_column(
        String(30), nullable=False,
        comment="Enum: dry | slightly_wet | moderately_wet | saturated"
    )

    # Device telemetry recorded with this reading
    battery_percent: Mapped[float]  = mapped_column(Float, nullable=False)
    device_status:   Mapped[str]    = mapped_column(
        String(20), nullable=False,
        comment="Enum: online | offline | maintenance"
    )

    # When the sensor reading was captured (not when it was stored in the DB)
    recorded_at: Mapped[datetime] = mapped_column(DateTime, nullable=False, index=True)

    # When the record was inserted into the database
    created_at: Mapped[datetime] = mapped_column(
        DateTime, server_default=func.now(), nullable=False
    )

    # ── Relationship back to Patient ──────────────────────────
    patient: Mapped["Patient"] = relationship("Patient", back_populates="urination_events")

    def __repr__(self) -> str:
        return (
            f"<UrinationEvent id={self.id} "
            f"patient_id={self.patient_id} "
            f"wetness={self.wetness_percent}%>"
        )


