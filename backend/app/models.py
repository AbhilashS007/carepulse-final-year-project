"""
CarePulse Backend — models.py
------------------------------
SQLAlchemy ORM models for all four database tables:
    1. Patient
    2. Alert
    3. UrinationEvent
    4. AIInsight

Design notes:
- Primary keys use Integer autoincrement (compatible with both SQLite and MySQL).
- String lengths are explicit (e.g., String(100)) so MySQL can enforce them.
- Enums are stored as VARCHAR strings so values are human-readable in the DB.
- Timestamps use server_default=func.now() so the database engine sets them,
  making migration to MySQL or PostgreSQL straightforward.
- All relationships are defined with back_populates for bidirectional access.
"""

import enum
from datetime import date, datetime

from sqlalchemy import (
    Boolean,
    Date,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base


# ================================================================
# ENUMS
# Values stored as strings in the database — readable & portable.
# ================================================================

class WetnessLevel(str, enum.Enum):
    """How saturated the diaper currently is."""
    DRY            = "dry"
    SLIGHTLY_WET   = "slightly_wet"
    MODERATELY_WET = "moderately_wet"
    SATURATED      = "saturated"


class DeviceStatus(str, enum.Enum):
    """Current connectivity state of the IoT sensor."""
    ONLINE      = "online"
    OFFLINE     = "offline"
    MAINTENANCE = "maintenance"


class AlertType(str, enum.Enum):
    """Category of the alert generated by the system."""
    HIGH_WETNESS   = "high_wetness"
    LOW_BATTERY    = "low_battery"
    DEVICE_OFFLINE = "device_offline"
    DIAPER_CHANGED = "diaper_changed"
    CHECK_REQUIRED = "check_required"


class AlertSeverity(str, enum.Enum):
    """Urgency level of an alert."""
    CRITICAL = "critical"
    WARNING  = "warning"
    INFO     = "info"


class RiskLevel(str, enum.Enum):
    """AI-computed patient health risk bucket."""
    LOW      = "low"
    MODERATE = "moderate"
    HIGH     = "high"
    CRITICAL = "critical"


class TrendDirection(str, enum.Enum):
    """Direction of urination frequency trend compared to previous week."""
    UP     = "up"
    DOWN   = "down"
    STABLE = "stable"


# ================================================================
# TABLE 1: patients
# ================================================================

class Patient(Base):
    """
    Represents a patient being monitored by CarePulse.

    Each patient is assigned one IoT diaper sensor (device_id).
    A patient can have many alerts, urination events, and AI insights.
    """

    __tablename__ = "patients"

    # Primary key
    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)

    # Personal details
    name:      Mapped[str] = mapped_column(String(100), nullable=False)
    age:       Mapped[int] = mapped_column(Integer, nullable=False)

    # Location within the hospital
    ward: Mapped[str] = mapped_column(String(100), nullable=False)
    room: Mapped[str] = mapped_column(String(20),  nullable=False)

    # Medical information
    condition:      Mapped[str]  = mapped_column(String(200), nullable=False)
    caregiver_name: Mapped[str]  = mapped_column(String(100), nullable=False)
    notes:          Mapped[str | None] = mapped_column(Text, nullable=True)

    # IoT device — stored as a string identifier (e.g., "CP-DEV-001")
    # This can be promoted to a FK if a separate devices table is added later.
    device_id: Mapped[str] = mapped_column(String(50), unique=True, nullable=False)

    # ── Archive flag (soft delete) ────────────────────────────
    # Never permanently delete patient records.
    # Archived patients are hidden from active views but fully preserved.
    is_archived: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    # ── Disease Profile (Phase 2 Gemini Clinical Insights readiness) ─
    # Structured, machine-readable fields consumed by the AI engine.
    # Separate from 'condition' (free-text clinical note for caregivers).
    #
    #   disease          → canonical disease name (e.g., "Chronic Kidney Disease")
    #   disease_severity → controlled enum: mild | moderate | severe | critical
    #   diagnosis_date   → ISO date the disease was diagnosed;
    #                       enables duration calculations in Gemini prompts
    disease:          Mapped[str | None] = mapped_column(
        String(200), nullable=True,
        comment="Canonical disease name for AI-assisted clinical analysis"
    )
    disease_severity: Mapped[str | None] = mapped_column(
        String(20), nullable=True,
        comment="Enum: mild | moderate | severe | critical"
    )
    diagnosis_date:   Mapped[date | None] = mapped_column(
        Date, nullable=True,
        comment="Date of formal disease diagnosis — used to compute disease_duration_days in AI prompts"
    )

    # Timestamps
    # server_default uses the DB engine clock — works on SQLite, MySQL, and PostgreSQL.
    created_at: Mapped[datetime] = mapped_column(
        DateTime, server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, server_default=func.now(), onupdate=func.now(), nullable=False
    )

    # ── Relationships ─────────────────────────────────────────
    # One patient → many alerts
    alerts: Mapped[list["Alert"]] = relationship(
        "Alert", back_populates="patient", cascade="all, delete-orphan"
    )

    # One patient → many urination events
    urination_events: Mapped[list["UrinationEvent"]] = relationship(
        "UrinationEvent", back_populates="patient", cascade="all, delete-orphan"
    )

    # One patient → many AI insight records
    ai_insights: Mapped[list["AIInsight"]] = relationship(
        "AIInsight", back_populates="patient", cascade="all, delete-orphan"
    )

    def __repr__(self) -> str:
        return f"<Patient id={self.id} name={self.name!r}>"


# ================================================================
# TABLE 2: alerts
# ================================================================

class Alert(Base):
    """
    An alert generated when a patient's sensor reading crosses
    a configured threshold (e.g., wetness > 75%, battery < 25%).

    Alerts are created automatically by the monitoring logic and
    resolved manually by caregivers via the dashboard.
    """

    __tablename__ = "alerts"

    # Primary key
    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)

    # Foreign key to the patient this alert belongs to.
    # ON DELETE CASCADE: if a patient is deleted, their alerts are deleted too.
    patient_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("patients.id", ondelete="CASCADE"), nullable=False, index=True
    )

    # Alert classification
    alert_type: Mapped[str] = mapped_column(
        String(50), nullable=False,
        comment="Enum: high_wetness | low_battery | device_offline | diaper_changed | check_required"
    )
    severity: Mapped[str] = mapped_column(
        String(20), nullable=False,
        comment="Enum: critical | warning | info"
    )

    # Human-readable description sent to the caregiver
    message: Mapped[str] = mapped_column(Text, nullable=False)

    # Resolution tracking
    resolved:    Mapped[bool]          = mapped_column(Boolean, default=False, nullable=False)
    resolved_at: Mapped[datetime|None] = mapped_column(DateTime, nullable=True)

    # Timestamp when the alert was first triggered
    created_at: Mapped[datetime] = mapped_column(
        DateTime, server_default=func.now(), nullable=False, index=True
    )

    # ── Relationship back to Patient ──────────────────────────
    patient: Mapped["Patient"] = relationship("Patient", back_populates="alerts")

    def __repr__(self) -> str:
        return f"<Alert id={self.id} type={self.alert_type!r} severity={self.severity!r}>"


