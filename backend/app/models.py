# TABLE 4: ai_insights
# ================================================================

class AIInsight(Base):
    """
    An AI-generated health insight record for a patient.

    Insights are periodically computed (e.g., once per hour) by
    analysing the patient's urination_events time-series data.
    Each record captures a full snapshot of the analysis output.

    Fields:
    - risk_score:        0–100 numerical risk score
    - risk_level:        Bucketed risk label (low / moderate / high / critical)
    - trend_direction:   Whether urination frequency is going up, down, or stable
    - trend_percent:     % change vs. previous week
    - insight_text:      Detailed AI-generated clinical observation
    - recommendation:    Suggested caregiver action
    - confidence:        Model confidence in this prediction (0–100 %)
    - tags:              Comma-separated clinical category tags
                         (e.g., "Renal,Nocturia,Urgent")
    """

    __tablename__ = "ai_insights"

    # Primary key
    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)

    # Foreign key to the patient this insight is about
    patient_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("patients.id", ondelete="CASCADE"), nullable=False, index=True
    )

    # Risk quantification
    risk_score: Mapped[int] = mapped_column(
        Integer, nullable=False,
        comment="Numerical risk score from 0 (no risk) to 100 (critical)"
    )
    risk_level: Mapped[str] = mapped_column(
        String(20), nullable=False,
        comment="Enum: low | moderate | high | critical"
    )

    # Trend analysis
    trend_direction: Mapped[str] = mapped_column(
        String(10), nullable=False,
        comment="Enum: up | down | stable — compared to previous 7 days"
    )
    trend_percent: Mapped[float] = mapped_column(
        Float, nullable=False,
        comment="Percentage change in urination frequency vs. previous week"
    )

    # AI-generated text content
    insight_text:   Mapped[str] = mapped_column(Text, nullable=False)
    risk_explanation: Mapped[str | None] = mapped_column(Text, nullable=True)
    recommendation: Mapped[str] = mapped_column(Text, nullable=False)
    monitoring_advice: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Model metadata
    confidence: Mapped[float] = mapped_column(
        Float, nullable=False,
        comment="AI model confidence in this insight (0–100 %)"
    )

    # Comma-separated clinical tags (e.g., "Renal,Nocturia,Urgent").
    # Simple format avoids a separate join table for Phase 1.
    # Can be normalised into a tags table in a later phase.
    tags: Mapped[str | None] = mapped_column(
        String(500), nullable=True,
        comment="Comma-separated clinical tags, e.g. 'Renal,Nocturia,Urgent'"
    )

    # When the AI model generated this insight (may differ from DB insert time)
    generated_at: Mapped[datetime] = mapped_column(DateTime, nullable=False, index=True)

    # When the record was inserted into the database
    created_at: Mapped[datetime] = mapped_column(
        DateTime, server_default=func.now(), nullable=False
    )

    # ── Relationship back to Patient ──────────────────────────
    patient: Mapped["Patient"] = relationship("Patient", back_populates="ai_insights")

    def __repr__(self) -> str:
        return (
            f"<AIInsight id={self.id} "
            f"patient_id={self.patient_id} "
            f"risk={self.risk_score} risk_level={self.risk_level!r}>"
        )


